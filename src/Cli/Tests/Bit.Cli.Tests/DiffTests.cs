using Bit.Cli.Projects;
using Bit.Cli.Templates;

namespace Bit.Cli.Tests;

[TestClass]
public class DiffTests
{
    [TestMethod]
    public void TheReadme_Should_GiveTheVersionNameOptionsAndPassword()
    {
        var record = TemplateDiff.ReadReadme("""
            ## Welcome!

            This project is generated by bit Contoso v-10.7.0-pre-02 using the following command:

            ```bash
                bit new Contoso
                        --database PostgreSQL
                        --module Admin
                        --aspire false
                        --sample
            ```

            pre-confirmed accounts whose password is **`40817263`**:
            """);

        Assert.AreEqual("10.7.0-pre-02", record.Version);
        Assert.AreEqual("Contoso", record.Name);
        Assert.AreEqual("40817263", record.SeedPassword);
        CollectionAssert.AreEquivalent(new Dictionary<string, string> { ["database"] = "PostgreSQL", ["module"] = "Admin", ["aspire"] = "false", ["sample"] = "true" }, record.Options.ToDictionary());
    }

    [TestMethod]
    public void AnOlderReadme_Should_GiveTheDotnetNewCommand()
    {
        var record = TemplateDiff.ReadReadme("""
            This project gets generated by bit Contoso v-9.11.2 using the following command
            ```bash
            dotnet new bit-bp --name Contoso --database SqlServer --signalR
            ```
            """);

        Assert.AreEqual("9.11.2", record.Version);
        Assert.AreEqual("Contoso", record.Name);
        Assert.IsNull(record.SeedPassword);
        CollectionAssert.AreEquivalent(new Dictionary<string, string> { ["database"] = "SqlServer", ["signalR"] = "true" }, record.Options.ToDictionary());
    }

    [TestMethod]
    public void EachVersion_Should_GetOnlyTheOptionsItHas()
    {
        var options = new Dictionary<string, string> { ["database"] = "postgresql", ["madeUp"] = "true", ["module"] = "Nope" };

        var (arguments, unknown) = TemplateDiff.TemplateArguments(TemplateManifest.Embedded, options);

        CollectionAssert.AreEqual(new[] { "--database", "PostgreSQL" }, arguments);
        CollectionAssert.AreEquivalent(new[] { "--madeUp true", "--module Nope" }, unknown);
    }
}
