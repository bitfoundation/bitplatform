namespace Bit.BlazorUI;

/// <summary>
/// The quarter turns an icon can be rendered at.
/// </summary>
public enum BitIconRotate
{
    /// <summary>
    /// A quarter turn clockwise.
    /// </summary>
    Rotate90,

    /// <summary>
    /// A half turn.
    /// </summary>
    Rotate180,

    /// <summary>
    /// A quarter turn counter-clockwise.
    /// </summary>
    Rotate270
}
