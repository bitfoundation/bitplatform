namespace Bit.BlazorUI;

public class BitToggleClassStyles
{
    /// <summary>
    /// Custom CSS classes/styles for the root element of the BitToggle.
    /// </summary>
    public string? Root { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the label of the BitToggle.
    /// </summary>
    public string? Label { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the description of the BitToggle.
    /// </summary>
    public string? Description { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the container of the BitToggle.
    /// </summary>
    public string? Container { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the button of the BitToggle.
    /// </summary>
    public string? Button { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the checked state of the BitToggle.
    /// </summary>
    public string? Checked { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the content rendered inside the track of the BitToggle.
    /// </summary>
    public string? Content { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the ON side of the content rendered inside the track of the BitToggle.
    /// </summary>
    public string? OnContent { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the OFF side of the content rendered inside the track of the BitToggle.
    /// </summary>
    public string? OffContent { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the thumb of the BitToggle.
    /// </summary>
    public string? Thumb { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the icon rendered inside the thumb of the BitToggle.
    /// </summary>
    public string? Icon { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the loading spinner of the BitToggle.
    /// </summary>
    public string? Spinner { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the text of the BitToggle.
    /// </summary>
    public string? Text { get; set; }
}
