namespace Bit.BlazorUI;

public class BitListBoxClassStyles
{
    /// <summary>
    /// Custom CSS classes/styles for the root element of the BitListBox.
    /// </summary>
    public string? Root { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the label of the BitListBox.
    /// </summary>
    public string? Label { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the list (the listbox element) of the BitListBox.
    /// </summary>
    public string? List { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for each item of the BitListBox.
    /// </summary>
    public string? Item { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for each selected item of the BitListBox.
    /// </summary>
    public string? SelectedItem { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the check box of each item of a multi select BitListBox.
    /// </summary>
    public string? Check { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the icon of each item of the BitListBox.
    /// </summary>
    public string? Icon { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the text of each item of the BitListBox.
    /// </summary>
    public string? Text { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the description of each item of the BitListBox.
    /// </summary>
    public string? Description { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the error message of the BitListBox.
    /// </summary>
    public string? ErrorMessage { get; set; }
}
