namespace Bit.BlazorUI;

public class BitNavBarClassStyles
{
    /// <summary>
    /// Custom CSS classes/styles for the root element of the BitNavBar.
    /// </summary>
    public string? Root { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the container of the items of the BitNavBar.
    /// </summary>
    public string? Container { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the footer of the BitNavBar, rendered after the items.
    /// </summary>
    public string? Footer { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the header of the BitNavBar, rendered before the items.
    /// </summary>
    public string? Header { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the item of the BitNavBar.
    /// </summary>
    public string? Item { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the badge (or the dot) of the item of the BitNavBar.
    /// </summary>
    public string? ItemBadge { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the item icon of the BitNavBar.
    /// </summary>
    public string? ItemIcon { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the wrapper of the icon and the badge of the item of the BitNavBar.
    /// </summary>
    public string? ItemIconContainer { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the item text of the BitNavBar.
    /// </summary>
    public string? ItemText { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the list item wrapping each item of the BitNavBar.
    /// </summary>
    public string? ItemWrapper { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the selected item of the BitNavBar.
    /// </summary>
    public string? SelectedItem { get; set; }
}
