namespace Bit.BlazorUI;

public class BitAccordionClassStyles
{
    /// <summary>
    /// Custom CSS classes/styles for the root element of the BitAccordion.
    /// </summary>
    public string? Root { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the expanded state of the BitAccordion.
    /// </summary>
    public string? Expanded { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the header wrapper of the BitAccordion, which holds the heading and the actions.
    /// </summary>
    public string? HeaderWrapper { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the heading element of the BitAccordion that wraps the header button.
    /// </summary>
    public string? Heading { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the header of the BitAccordion.
    /// </summary>
    public string? Header { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the icon at the start of the header of the BitAccordion.
    /// </summary>
    public string? Icon { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the header content of the BitAccordion.
    /// </summary>
    public string? HeaderContent { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the title of the BitAccordion.
    /// </summary>
    public string? Title { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the description of the BitAccordion.
    /// </summary>
    public string? Description { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the expander icon wrapper of the BitAccordion.
    /// </summary>
    public string? ExpanderIconWrapper { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the expander icon of the BitAccordion.
    /// </summary>
    public string? ExpanderIcon { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the icon of the BitAccordion in expanded state.
    /// </summary>
    public string? ExpandedIcon { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the actions of the BitAccordion, rendered beside the header.
    /// </summary>
    public string? Actions { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the content container of the BitAccordion.
    /// </summary>
    public string? ContentContainer { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the content wrapper of the BitAccordion, which clips the content while it collapses.
    /// </summary>
    public string? ContentWrapper { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the content of the BitAccordion.
    /// </summary>
    public string? Content { get; set; }
}
