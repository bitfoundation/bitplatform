namespace Bit.BlazorUI;

public class BitPanelClassStyles
{
    /// <summary>
    /// Custom CSS classes/styles for the root element of the BitPanel.
    /// </summary>
    public string? Root { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the overlay of the BitPanel.
    /// </summary>
    public string? Overlay { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the container of the BitPanel.
    /// </summary>
    public string? Container { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the header container of the BitPanel, which holds the header beside the
    /// close button.
    /// </summary>
    public string? HeaderContainer { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the header of the BitPanel.
    /// </summary>
    public string? Header { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the close button of the BitPanel.
    /// </summary>
    public string? CloseButton { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the icon of the close button of the BitPanel.
    /// </summary>
    public string? CloseIcon { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the body of the BitPanel, which is the part that scrolls between the
    /// header and the footer.
    /// </summary>
    public string? Body { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the footer of the BitPanel.
    /// </summary>
    public string? Footer { get; set; }
}
