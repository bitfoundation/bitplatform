namespace Bit.BlazorUI;

/// <summary>
/// The custom CSS classes and styles of the different parts of the BitSwiper.
/// </summary>
public class BitSwiperClassStyles
{
    /// <summary>
    /// Custom CSS classes/styles for the root element of the BitSwiper.
    /// </summary>
    public string? Root { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the scrolling container of the BitSwiper.
    /// </summary>
    public string? Container { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the items of the BitSwiper.
    /// </summary>
    public string? Item { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the item of the BitSwiper the swiper is currently standing on.
    /// </summary>
    public string? CurrentItem { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the next/prev buttons of the BitSwiper.
    /// </summary>
    public string? Buttons { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the icons of the next/prev buttons of the BitSwiper.
    /// </summary>
    public string? ButtonIcons { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the next button of the BitSwiper.
    /// </summary>
    public string? NextButton { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the icon of the next button of the BitSwiper.
    /// </summary>
    public string? NextButtonIcon { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the previous button of the BitSwiper.
    /// </summary>
    public string? PrevButton { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the icon of the previous button of the BitSwiper.
    /// </summary>
    public string? PrevButtonIcon { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the dots container of the BitSwiper.
    /// </summary>
    public string? DotsContainer { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the dot elements of the BitSwiper.
    /// </summary>
    public string? Dots { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the current dot element of the BitSwiper.
    /// </summary>
    public string? CurrentDot { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the play/pause button of the BitSwiper.
    /// </summary>
    public string? PlayPauseButton { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the icon of the play/pause button of the BitSwiper.
    /// </summary>
    public string? PlayPauseButtonIcon { get; set; }
}
