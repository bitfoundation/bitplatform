namespace Bit.BlazorUI;

public class BitLayoutClassStyles
{
    /// <summary>
    /// Custom CSS classes/styles for the root element of the BitLayout.
    /// </summary>
    public string? Root { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the skip link of the BitLayout.
    /// </summary>
    public string? SkipLink { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the header section of the BitLayout.
    /// </summary>
    public string? Header { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the middle row of the BitLayout that holds the nav panel, the main content and the aside.
    /// </summary>
    public string? Main { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the nav panel section of the BitLayout.
    /// </summary>
    public string? NavPanel { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the main-content section of the BitLayout.
    /// </summary>
    public string? MainContent { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the aside section of the BitLayout.
    /// </summary>
    public string? Aside { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the footer section of the BitLayout.
    /// </summary>
    public string? Footer { get; set; }
}
