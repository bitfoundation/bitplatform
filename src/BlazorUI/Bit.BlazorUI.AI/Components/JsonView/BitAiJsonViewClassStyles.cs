namespace Bit.BlazorUI;

public class BitAiJsonViewClassStyles
{
    /// <summary>
    /// Custom CSS classes/styles for the root element of the BitAiJsonView.
    /// </summary>
    public string? Root { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for every row of the BitAiJsonView.
    /// </summary>
    public string? Row { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the toggle buttons that expand and collapse the containers of the BitAiJsonView.
    /// </summary>
    public string? Toggle { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the chevron icon of the toggle buttons of the BitAiJsonView.
    /// </summary>
    public string? ToggleIcon { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the indented group of the entries of an open container of the BitAiJsonView.
    /// </summary>
    public string? Group { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the property keys of the BitAiJsonView.
    /// </summary>
    public string? Key { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the string values of the BitAiJsonView.
    /// </summary>
    public string? String { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the number values of the BitAiJsonView.
    /// </summary>
    public string? Number { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the true and false values of the BitAiJsonView.
    /// </summary>
    public string? Boolean { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the null values of the BitAiJsonView.
    /// </summary>
    public string? Null { get; set; }
}
