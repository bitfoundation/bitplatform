namespace Bit.BlazorUI;

public class BitAiDataTableClassStyles
{
    /// <summary>
    /// Custom CSS classes/styles for the root element of the BitAiDataTable, the box the table scrolls in.
    /// </summary>
    public string? Root { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the table element of the BitAiDataTable.
    /// </summary>
    public string? Table { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the header row of the BitAiDataTable.
    /// </summary>
    public string? HeaderRow { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for each header cell of the BitAiDataTable.
    /// </summary>
    public string? HeaderCell { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for each body row of the BitAiDataTable.
    /// </summary>
    public string? Row { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for each body cell of the BitAiDataTable.
    /// </summary>
    public string? Cell { get; set; }
}
