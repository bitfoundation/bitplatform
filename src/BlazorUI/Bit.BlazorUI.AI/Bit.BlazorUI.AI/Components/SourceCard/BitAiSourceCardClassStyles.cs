namespace Bit.BlazorUI;

public class BitAiSourceCardClassStyles
{
    /// <summary>
    /// Custom CSS classes/styles for the root element of the BitAiSourceCard.
    /// </summary>
    public string? Root { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the BitCard of the BitAiSourceCard.
    /// </summary>
    public BitCardClassStyles? Card { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the content (the number and the body) of the BitAiSourceCard.
    /// </summary>
    public string? Content { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the marker number of the BitAiSourceCard.
    /// </summary>
    public string? Index { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the body (the title and the site) of the BitAiSourceCard.
    /// </summary>
    public string? Body { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the title of the BitAiSourceCard.
    /// </summary>
    public string? Title { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the site line of the BitAiSourceCard.
    /// </summary>
    public string? Site { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the favicon of the BitAiSourceCard.
    /// </summary>
    public string? Favicon { get; set; }
}
