namespace Bit.BlazorUI;

public class BitTimeZonePickerClassStyles
{
    /// <summary>
    /// Custom CSS classes/styles for the root element of the BitTimeZonePicker.
    /// </summary>
    public string? Root { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the label of the BitTimeZonePicker.
    /// </summary>
    public string? Label { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the field (the button that opens the time zone list) of the BitTimeZonePicker.
    /// </summary>
    public string? Field { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the content of the field (the offset and the name of the selected time zone, or the placeholder) of the BitTimeZonePicker.
    /// </summary>
    public string? Text { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the offset from UTC of the time zones in the field and in the list of the BitTimeZonePicker.
    /// </summary>
    public string? Offset { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the caret down element of the field of the BitTimeZonePicker.
    /// </summary>
    public string? Caret { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the container of the error message of the BitTimeZonePicker.
    /// </summary>
    public string? ErrorMessageContainer { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the error message of the BitTimeZonePicker.
    /// </summary>
    public string? ErrorMessage { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the container of the description of the BitTimeZonePicker.
    /// </summary>
    public string? DescriptionContainer { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the description of the BitTimeZonePicker.
    /// </summary>
    public string? Description { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the overlay of the time zone list of the BitTimeZonePicker.
    /// </summary>
    public string? Overlay { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the callout of the time zone list of the BitTimeZonePicker.
    /// </summary>
    public string? Callout { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the search box of the time zone list of the BitTimeZonePicker.
    /// </summary>
    public string? SearchBox { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the scroll container of the time zone list of the BitTimeZonePicker.
    /// </summary>
    public string? ScrollContainer { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the list (the listbox element) of the BitTimeZonePicker.
    /// </summary>
    public string? List { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for each item of the time zone list of the BitTimeZonePicker.
    /// </summary>
    public string? Item { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the name of each item of the time zone list of the BitTimeZonePicker.
    /// </summary>
    public string? ItemName { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the country name of each item of the time zone list of the BitTimeZonePicker.
    /// </summary>
    public string? ItemCountry { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the no results message of the time zone list of the BitTimeZonePicker.
    /// </summary>
    public string? NoResults { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the label container of the responsive panel of the time zone list of the BitTimeZonePicker.
    /// </summary>
    public string? ResponsiveLabelContainer { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the label of the responsive panel of the time zone list of the BitTimeZonePicker.
    /// </summary>
    public string? ResponsiveLabel { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the close button of the responsive panel of the time zone list of the BitTimeZonePicker.
    /// </summary>
    public string? ResponsiveCloseButton { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the icon of the close button of the responsive panel of the time zone list of the BitTimeZonePicker.
    /// </summary>
    public string? ResponsiveCloseIcon { get; set; }
}
