namespace Bit.BlazorUI;

public class BitPopConfirmClassStyles
{
    /// <summary>
    /// Custom CSS classes/styles for the root element of the BitPopConfirm, which holds the trigger.
    /// </summary>
    public string? Root { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the popup of the BitPopConfirm.
    /// </summary>
    public string? Callout { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the container of the content of the popup of the BitPopConfirm.
    /// </summary>
    public string? Container { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the title of the BitPopConfirm.
    /// </summary>
    public string? Title { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the message of the BitPopConfirm.
    /// </summary>
    public string? Message { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the container of the buttons of the BitPopConfirm.
    /// </summary>
    public string? Actions { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the Cancel button of the BitPopConfirm.
    /// </summary>
    public string? CancelButton { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the Confirm button of the BitPopConfirm.
    /// </summary>
    public string? ConfirmButton { get; set; }
}
