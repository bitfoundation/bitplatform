namespace Bit.BlazorUI;

public class BitCountryPickerClassStyles
{
    /// <summary>
    /// Custom CSS classes/styles for the root element of the BitCountryPicker.
    /// </summary>
    public string? Root { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the label of the BitCountryPicker.
    /// </summary>
    public string? Label { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the field (the button that opens the country list) of the BitCountryPicker.
    /// </summary>
    public string? Field { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the content of the field (the flag and the name of the selected country, or the placeholder) of the BitCountryPicker.
    /// </summary>
    public string? Text { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the flag image of the countries of the BitCountryPicker.
    /// </summary>
    public string? Flag { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the caret down element of the field of the BitCountryPicker.
    /// </summary>
    public string? Caret { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the container of the error message of the BitCountryPicker.
    /// </summary>
    public string? ErrorMessageContainer { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the error message of the BitCountryPicker.
    /// </summary>
    public string? ErrorMessage { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the container of the description of the BitCountryPicker.
    /// </summary>
    public string? DescriptionContainer { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the description of the BitCountryPicker.
    /// </summary>
    public string? Description { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the overlay of the country list of the BitCountryPicker.
    /// </summary>
    public string? Overlay { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the callout of the country list of the BitCountryPicker.
    /// </summary>
    public string? Callout { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the search box of the country list of the BitCountryPicker.
    /// </summary>
    public string? SearchBox { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the scroll container of the country list of the BitCountryPicker.
    /// </summary>
    public string? ScrollContainer { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the list (the listbox element) of the BitCountryPicker.
    /// </summary>
    public string? List { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for each item of the country list of the BitCountryPicker.
    /// </summary>
    public string? Item { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the name of each item of the country list of the BitCountryPicker.
    /// </summary>
    public string? ItemName { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the no results message of the country list of the BitCountryPicker.
    /// </summary>
    public string? NoResults { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the label container of the responsive panel of the country list of the BitCountryPicker.
    /// </summary>
    public string? ResponsiveLabelContainer { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the label of the responsive panel of the country list of the BitCountryPicker.
    /// </summary>
    public string? ResponsiveLabel { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the close button of the responsive panel of the country list of the BitCountryPicker.
    /// </summary>
    public string? ResponsiveCloseButton { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the icon of the close button of the responsive panel of the country list of the BitCountryPicker.
    /// </summary>
    public string? ResponsiveCloseIcon { get; set; }
}
