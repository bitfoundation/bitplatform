namespace Bit.BlazorUI;

/// <summary>
/// Custom CSS classes/styles for different parts of the <see cref="BitRichTextEditor"/>.
/// </summary>
public class BitRichTextEditorClassStyles
{
    /// <summary>
    /// Custom CSS classes/styles for the root of the BitRichTextEditor.
    /// </summary>
    public string? Root { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the label of the BitRichTextEditor.
    /// </summary>
    public string? Label { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the toolbar of the BitRichTextEditor.
    /// </summary>
    public string? Toolbar { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the toolbar groups of the BitRichTextEditor.
    /// </summary>
    public string? Group { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the toolbar buttons of the BitRichTextEditor.
    /// </summary>
    public string? Button { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the tool panels (link, image, media, table, find, emoji, color and keyboard help) of the BitRichTextEditor.
    /// </summary>
    public string? Panel { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the floating selection toolbar of the BitRichTextEditor.
    /// </summary>
    public string? QuickToolbar { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the slash command and mention menus of the BitRichTextEditor.
    /// </summary>
    public string? Menu { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the inline error banner (a failed command, link or upload) of the BitRichTextEditor.
    /// </summary>
    public string? Error { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the editor (content) area of the BitRichTextEditor.
    /// </summary>
    public string? Editor { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the HTML source view textarea of the BitRichTextEditor.
    /// </summary>
    public string? Source { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the error message (the ErrorMessage parameter) of the BitRichTextEditor.
    /// </summary>
    public string? ErrorMessage { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the footer row (holding the description and the counts) of the BitRichTextEditor.
    /// </summary>
    public string? Footer { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the description (helper text) in the footer of the BitRichTextEditor.
    /// </summary>
    public string? Description { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the character/word counts in the footer of the BitRichTextEditor.
    /// </summary>
    public string? Count { get; set; }
}
