namespace Bit.BlazorUI;

/// <summary>
/// Custom CSS classes/styles for different parts of the <see cref="BitPdfViewer"/>.
/// </summary>
public class BitPdfViewerClassStyles
{
    /// <summary>
    /// Custom CSS classes/styles for the root element of the BitPdfViewer.
    /// </summary>
    public string? Root { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the indeterminate loading bar of the BitPdfViewer.
    /// </summary>
    public string? ProgressBar { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the toolbar of the BitPdfViewer.
    /// </summary>
    public string? Toolbar { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the toolbar buttons of the BitPdfViewer.
    /// </summary>
    public string? ToolbarButton { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the document title shown in the toolbar of the BitPdfViewer.
    /// </summary>
    public string? Title { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the find box of the BitPdfViewer.
    /// </summary>
    public string? SearchBox { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the body (sidebar plus surface) of the BitPdfViewer.
    /// </summary>
    public string? Body { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the thumbnails sidebar of the BitPdfViewer.
    /// </summary>
    public string? Thumbnails { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for each thumbnail of the BitPdfViewer.
    /// </summary>
    public string? Thumbnail { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the bookmarks sidebar of the BitPdfViewer.
    /// </summary>
    public string? Outline { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for each bookmark of the BitPdfViewer.
    /// </summary>
    public string? OutlineItem { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the attachments sidebar of the BitPdfViewer.
    /// </summary>
    public string? Attachments { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for each attachment of the BitPdfViewer.
    /// </summary>
    public string? Attachment { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the layers sidebar of the BitPdfViewer.
    /// </summary>
    public string? Layers { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for each layer row of the BitPdfViewer.
    /// </summary>
    public string? Layer { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the scrollable document surface of the BitPdfViewer.
    /// </summary>
    public string? Surface { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for each rendered page of the BitPdfViewer.
    /// </summary>
    public string? Page { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the document properties dialog of the BitPdfViewer.
    /// </summary>
    public string? PropertiesDialog { get; set; }
}
