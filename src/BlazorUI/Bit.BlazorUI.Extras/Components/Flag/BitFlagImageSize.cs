    /// </summary>
    Size24,

    /// <summary>
    /// The 32 pixel image.
    /// </summary>
    Size32,

    /// <summary>
    /// The 48 pixel image.
    /// </summary>
    Size48,

    /// <summary>
    /// The 64 pixel image.
    /// </summary>
    Size64
}
