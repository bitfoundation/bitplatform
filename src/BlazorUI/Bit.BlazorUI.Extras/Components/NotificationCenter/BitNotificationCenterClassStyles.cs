namespace Bit.BlazorUI;

public class BitNotificationCenterClassStyles
{
    /// <summary>
    /// Custom CSS classes/styles for the root element of the BitNotificationCenter.
    /// </summary>
    public string? Root { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the bell button of the BitNotificationCenter.
    /// </summary>
    public string? Button { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the bell icon of the BitNotificationCenter.
    /// </summary>
    public string? Icon { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the unread count badge on the bell of the BitNotificationCenter.
    /// </summary>
    public string? Badge { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the callout the panel of the BitNotificationCenter opens in.
    /// </summary>
    public string? Callout { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the panel of the BitNotificationCenter.
    /// </summary>
    public string? Panel { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the header of the panel of the BitNotificationCenter.
    /// </summary>
    public string? Header { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the header text of the panel of the BitNotificationCenter.
    /// </summary>
    public string? HeaderText { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the clear all button of the BitNotificationCenter.
    /// </summary>
    public string? ClearAllButton { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the list of notifications of the BitNotificationCenter.
    /// </summary>
    public string? List { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for each notification of the BitNotificationCenter.
    /// </summary>
    public string? Item { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for each notification of the BitNotificationCenter that had not been read when the
    /// panel opened.
    /// </summary>
    public string? UnreadItem { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the icon of each notification of the BitNotificationCenter.
    /// </summary>
    public string? ItemIcon { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the title of each notification of the BitNotificationCenter.
    /// </summary>
    public string? ItemTitle { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the body of each notification of the BitNotificationCenter.
    /// </summary>
    public string? ItemBody { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the time of each notification of the BitNotificationCenter.
    /// </summary>
    public string? ItemTime { get; set; }

    /// <summary>
    /// Custom CSS classes/styles for the text the panel of the BitNotificationCenter shows when there are no
    /// notifications.
    /// </summary>
    public string? Empty { get; set; }
}
