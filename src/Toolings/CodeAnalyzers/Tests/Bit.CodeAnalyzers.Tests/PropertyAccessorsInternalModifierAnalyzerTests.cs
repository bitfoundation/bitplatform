using Bit.CodeAnalyzers.SystemAnalyzers;
using static Bit.CodeAnalyzers.Tests.AnalyzerTestHarness;

namespace Bit.CodeAnalyzers.Tests;

[TestClass]
public class PropertyAccessorsInternalModifierAnalyzerTests
{
    private static Task<string[]> Analyze(string source)
    {
        return GetDiagnostics(new PropertyAccessorsInternalModifierAnalyzer(), source);
    }

    [TestMethod]
    public async Task ReportsInternalAccessorsOnTheModifier()
    {
        var diagnostics = await Analyze("""
            namespace App;

            public class Product
            {
                public string Name { get; internal set; } = "";

                public int Stock { internal get; set; }

                public decimal Price
                {
                    get => 0;
                    protected internal set { }
                }
            }
            """);

        AssertDiagnostics(diagnostics,
            "PropertyAccessorsInternalModifierAnalyzer: internal",
            "PropertyAccessorsInternalModifierAnalyzer: internal",
            "PropertyAccessorsInternalModifierAnalyzer: internal");
    }

    [TestMethod]
    public async Task ReportsInternalIndexerAccessors()
    {
        var diagnostics = await Analyze("""
            namespace App;

            public class Catalog
            {
                public string this[int index]
                {
                    get => "";
                    internal set { }
                }
            }
            """);

        AssertDiagnostics(diagnostics, "PropertyAccessorsInternalModifierAnalyzer: internal");
    }

    [TestMethod]
    public async Task AcceptsOtherAccessorsAndInternalProperties()
    {
        var diagnostics = await Analyze("""
            namespace App;

            public class Product
            {
                public string Name { get; private set; } = "";

                public int Stock { get; protected set; }

                public decimal Price { get; private protected set; }

                public string Code { get; init; } = "";

                internal string Notes { get; set; } = "";

                public string Display => Name;

                public event System.EventHandler Changed
                {
                    add { }
                    remove { }
                }
            }

            public record Item(string Name);
            """);

        AssertDiagnostics(diagnostics);
    }

    [TestMethod]
    public async Task ReportsInGeneratedCodeWhereRazorPutsCodeBlocks()
    {
        var diagnostics = await Analyze("""
            // <auto-generated/>
            namespace App;

            public partial class Counter
            {
                public int Count { get; internal set; }
            }
            """);

        AssertDiagnostics(diagnostics, "PropertyAccessorsInternalModifierAnalyzer: internal");
    }
}
