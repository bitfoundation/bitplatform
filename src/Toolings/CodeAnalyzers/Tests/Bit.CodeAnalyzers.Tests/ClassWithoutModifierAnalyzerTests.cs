using Bit.CodeAnalyzers.SystemAnalyzers;
using Microsoft.CodeAnalysis;
using static Bit.CodeAnalyzers.Tests.AnalyzerTestHarness;

namespace Bit.CodeAnalyzers.Tests;

[TestClass]
public class ClassWithoutModifierAnalyzerTests
{
    private static Task<string[]> Analyze(string source, OutputKind outputKind = OutputKind.DynamicallyLinkedLibrary)
    {
        return GetDiagnostics(new ClassWithoutModifierAnalyzer(), source, outputKind);
    }

    [TestMethod]
    public async Task ReportsClassWithoutModifiersOnItsName()
    {
        var diagnostics = await Analyze("""
            namespace App;

            class Helper
            {
                public void Run()
                {
                }
            }
            """);

        AssertDiagnostics(diagnostics, "ClassWithoutModifierAnalyzer: Helper");
    }

    [TestMethod]
    public async Task ReportsNestedClassesAndRecordsWithoutModifiers()
    {
        var diagnostics = await Analyze("""
            namespace App
            {
                public class Outer
                {
                    class Inner
                    {
                    }

                    record Item(int Id);

                    record class Entry(string Name);
                }
            }
            """);

        AssertDiagnostics(diagnostics,
            "ClassWithoutModifierAnalyzer: Inner",
            "ClassWithoutModifierAnalyzer: Item",
            "ClassWithoutModifierAnalyzer: Entry");
    }

    [TestMethod]
    public async Task AcceptsAnyModifier()
    {
        var diagnostics = await Analyze("""
            namespace App;

            public class PublicClass
            {
                private class PrivateClass
                {
                }

                protected internal record ProtectedRecord;
            }

            internal sealed class SealedClass
            {
            }

            static class StaticClass
            {
            }

            abstract class AbstractClass
            {
            }

            partial class PartialClass
            {
            }

            public partial class PartialClass
            {
            }

            file class FileClass
            {
            }

            sealed record SealedRecord(int Id);
            """);

        AssertDiagnostics(diagnostics);
    }

    [TestMethod]
    public async Task IgnoresClassesMarkedAsGeneratedCode()
    {
        var diagnostics = await Analyze("""
            namespace App;

            [System.CodeDom.Compiler.GeneratedCode("tool", "1.0")]
            class Generated
            {
            }
            """);

        AssertDiagnostics(diagnostics);
    }

    [TestMethod]
    public async Task IgnoresTypesThatAreNotClasses()
    {
        var diagnostics = await Analyze("""
            namespace App;

            struct Point
            {
            }

            interface IService
            {
            }

            enum Color
            {
                Red
            }

            record struct Size(int Width, int Height);

            delegate void Callback();
            """);

        AssertDiagnostics(diagnostics);
    }

    [TestMethod]
    public async Task ReportsClassesDeclaredNextToTopLevelStatements()
    {
        var diagnostics = await Analyze("""
            System.Console.WriteLine(new Helper());

            class Helper
            {
            }
            """, OutputKind.ConsoleApplication);

        AssertDiagnostics(diagnostics, "ClassWithoutModifierAnalyzer: Helper");
    }

    [TestMethod]
    public async Task ReportsInGeneratedCodeWhereRazorPutsCodeBlocks()
    {
        var diagnostics = await Analyze("""
            // <auto-generated/>
            namespace App;

            public partial class Counter
            {
                class State
                {
                }
            }
            """);

        AssertDiagnostics(diagnostics, "ClassWithoutModifierAnalyzer: State");
    }
}
